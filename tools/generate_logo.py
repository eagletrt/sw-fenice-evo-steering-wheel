#!/usr/bin/env python3
"""Generate the splash-screen logo as an RLE-compressed A8 alpha mask.

Rasterises assets/eagle-logo.svg with rsvg-convert at SPLASH logo width, keeps
the alpha channel (the logo is white on transparent) and writes
Core/Src/steering/splash-logo.c + Core/Inc/steering/splash-logo.h.

The output is committed: run this script again only when the logo or its
width change. Needs rsvg-convert (librsvg) and Pillow.

    python3 tools/generate_logo.py [--width 520]

RLE format (decoded by splash-api.c), one stream over width * height bytes,
row after row:
    control c < 128   -> c + 1 literal bytes follow
    control c >= 128  -> the next byte is repeated c - 125 times (3..130)
"""

import argparse
import io
import subprocess
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SVG_PATH = ROOT / "assets" / "eagle-logo.svg"
C_PATH = ROOT / "Core" / "Src" / "steering" / "splash-logo.c"
H_PATH = ROOT / "Core" / "Inc" / "steering" / "splash-logo.h"

LITERAL_MAX = 128
REPEAT_MIN = 3
REPEAT_MAX = 130


def rasterise(width: int) -> Image.Image:
    png = subprocess.run(
        ["rsvg-convert", "-w", str(width), str(SVG_PATH)], check=True, capture_output=True
    ).stdout
    alpha = Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")
    # Rounding can leave an empty row or column: crop so the size is the logo's.
    return alpha.crop(alpha.getbbox())


def encode(data: bytes) -> bytes:
    out = bytearray()
    literal = bytearray()

    def flush_literal() -> None:
        while literal:
            chunk = literal[:LITERAL_MAX]
            out.append(len(chunk) - 1)
            out.extend(chunk)
            del literal[:LITERAL_MAX]

    i = 0
    while i < len(data):
        run = 1
        while i + run < len(data) and data[i + run] == data[i] and run < REPEAT_MAX:
            run += 1
        if run >= REPEAT_MIN:
            flush_literal()
            out.append(run + 125)
            out.append(data[i])
        else:
            literal.extend(data[i : i + run])
        i += run
    flush_literal()
    return bytes(out)


def decode(rle: bytes, size: int) -> bytes:
    out = bytearray()
    i = 0
    while i < len(rle):
        control = rle[i]
        if control < LITERAL_MAX:
            out.extend(rle[i + 1 : i + 2 + control])
            i += 2 + control
        else:
            out.extend(bytes([rle[i + 1]]) * (control - 125))
            i += 2
    assert len(out) == size
    return bytes(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--width", type=int, default=520, help="logo width in pixels")
    args = parser.parse_args()

    alpha = rasterise(args.width)
    width, height = alpha.size
    raw = alpha.tobytes()
    rle = encode(raw)
    if decode(rle, len(raw)) != raw:
        print("RLE round trip failed", file=sys.stderr)
        return 1

    rows = []
    for start in range(0, len(rle), 16):
        rows.append("    " + ", ".join(f"0x{b:02X}" for b in rle[start : start + 16]) + ",")

    header = f"""/*!
 * \\file splash-logo.h
 * \\ingroup Core
 *
 * \\brief Team logo as an RLE-compressed A8 alpha mask.
 *
 * \\details Generated by tools/generate_logo.py from assets/eagle-logo.svg,
 *     do not edit by hand. The RLE format is described in that script.
 */

#ifndef SPLASH_LOGO_H
#define SPLASH_LOGO_H

#include <stdint.h>

#define SPLASH_LOGO_WIDTH ({width}U)  /*!< Width of the decoded mask, in pixels */
#define SPLASH_LOGO_HEIGHT ({height}U) /*!< Height of the decoded mask, in pixels */
#define SPLASH_LOGO_RLE_SIZE ({len(rle)}U) /*!< Size of splash_logo_rle, in bytes */

extern const uint8_t splash_logo_rle[SPLASH_LOGO_RLE_SIZE];

#endif // SPLASH_LOGO_H
"""
    source = (
        """/*!
 * \\file splash-logo.c
 * \\ingroup Core
 *
 * \\brief Team logo data, see splash-logo.h.
 *
 * \\details Generated by tools/generate_logo.py, do not edit by hand.
 */

#include "splash-logo.h"

// clang-format off
const uint8_t splash_logo_rle[SPLASH_LOGO_RLE_SIZE] = {
"""
        + "\n".join(rows)
        + "\n};\n// clang-format on\n"
    )

    H_PATH.write_text(header)
    C_PATH.write_text(source)
    # Same style as the rest of Core/ (the pre-commit hook would reformat it anyway).
    try:
        subprocess.run(["clang-format", "-i", str(H_PATH), str(C_PATH)], check=True)
    except (OSError, subprocess.CalledProcessError):
        print("clang-format not available, output left unformatted", file=sys.stderr)
    print(f"logo {width}x{height}: {len(raw)} bytes raw, {len(rle)} bytes RLE")
    return 0


if __name__ == "__main__":
    sys.exit(main())
